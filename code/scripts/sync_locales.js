/**
 * Programmatically generates typed TypeScript modules for each language.
 */
function syncLocales() {
    console.log('Synchronizing all 18 VS Code locale modules...');
    let count = 0;

    for (const [langKey, dict] of Object.entries(TRANSLATIONS)) {
        const targetFile = path.join(LOCALES_DIR, `${langKey}.ts`);
        const varName = langKey.replace(/[^a-zA-Z0-9]/g, '_');
        
        let tsContent = `import { Translations } from '../i18n';\n\n`;
        tsContent += `/**\n * Auto-generated translation dictionary for '${langKey}'.\n */\n`;
        tsContent += `export const ${varName}: Translations = ${JSON.stringify(dict, null, 4)};\n`;

        fs.writeFileSync(targetFile, tsContent, 'utf8');
        count++;
    }

    console.log(`Successfully generated and synchronized ${count} locale modules in: ${LOCALES_DIR}`);
}

syncLocales();
